# Writes <OutDir>\aqgc_aa_key.h with the Altitude Angel API key from the environment variable AQGC_AA_KEY
# (CE RED / EN 18031, 2026-11-17: the key is not in the public repository).
# CI: only tagged builds (simple_ui_* / v*) set AQGC_AA_KEY from the GitHub secret ALTITUDE_ANGEL_KEY.
# Local: set AQGC_AA_KEY and run this script with the shadow build directory before qmake.
# The key is stored XOR-masked with random bytes, so it is not a plain string in the binary. It can still be
# recovered from the app: rotate the key at Altitude Angel if it leaks. Never print the key.
param([Parameter(Mandatory = $true)][string]$OutDir)

$file = Join-Path $OutDir "aqgc_aa_key.h"
$key = $env:AQGC_AA_KEY
if ([string]::IsNullOrEmpty($key)) {
    if (Test-Path $file) { Remove-Item $file -Force }
    Write-Host "Altitude Angel key: not built in (AQGC_AA_KEY is empty)"
    exit 0
}

$data = [Text.Encoding]::UTF8.GetBytes($key)
$mask = New-Object byte[] $data.Length
[Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($mask)
$masked = for ($i = 0; $i -lt $data.Length; $i++) { $data[$i] -bxor $mask[$i] }
function Hex($bytes) { ($bytes | ForEach-Object { "0x{0:x2}" -f $_ }) -join "," }

$text = @"
// Generated by custom/tools/aakey/gen_aa_key.ps1 - do not commit.
#pragma once
static const unsigned char kAqgcAAKeyMask[] = { $(Hex $mask) };
static const unsigned char kAqgcAAKeyData[] = { $(Hex $masked) };
"@
New-Item -ItemType Directory -Force $OutDir | Out-Null
[IO.File]::WriteAllText($file, $text)
Write-Host "Altitude Angel key: built in ($($data.Length) bytes)"
