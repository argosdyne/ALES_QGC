#!/usr/bin/env python3
"""Generate src/uas/UASWarningPatterns.h from translations/qgc_source_ko_KR.ts.

StatusTextTranslator matches vehicle status texts that already contain values
(e.g. "Compass 2 not calibrated") against the printf-style keys of the
"UASWarning" translation context (e.g. "Compass %d not calibrated"). Qt's
translator cannot list its keys at runtime, so this script writes them into a
header. Run it again whenever UASWarning keys with placeholders are added.

Usage (from the repository root):
    python3 tools/generate_uaswarning_patterns.py
"""

import os
import re
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TS_FILE = os.path.join(REPO_ROOT, "translations", "qgc_source_ko_KR.ts")
OUT_FILE = os.path.join(REPO_ROOT, "src", "uas", "UASWarningPatterns.h")

CONVERSION = re.compile(rb"%[-+ #0]*\d*(?:\.\d+)?(?:hh|h|ll|l|z)?[diuoxXfFeEgGcs]")

HEADER = b"""/****************************************************************************
 *
 * (c) 2009-2020 QGROUNDCONTROL PROJECT <http://www.qgroundcontrol.org>
 *
 * QGroundControl is licensed according to the terms in the file
 * COPYING.md in the root of the source code directory.
 *
 ****************************************************************************/

#pragma once

// Generated by tools/generate_uaswarning_patterns.py from the "UASWarning" context
// of translations/qgc_source_ko_KR.ts. Do not edit by hand.
// These are the vehicle status text translation keys that contain printf-style
// conversions (%d, %s, %.1f, ...). They let StatusTextTranslator match a status
// text that the vehicle has already formatted (e.g. "Compass 2 not calibrated")
// against its translation key ("Compass %d not calibrated").

static const char* const kUASWarningPatternKeys[] = {
"""


def unescape_xml(text):
    for entity, char in ((b"&apos;", b"'"), (b"&quot;", b'"'), (b"&lt;", b"<"), (b"&gt;", b">"), (b"&amp;", b"&")):
        text = text.replace(entity, char)
    return text


def c_literal(key):
    """Escape a UTF-8 key as an ASCII-only C string literal body."""
    out = key.replace(b"\\", b"\\\\").replace(b'"', b'\\"').replace(b"\n", b"\\n").replace(b"\t", b"\\t")
    out = out.replace(b"??", b"?\\?")  # avoid trigraphs
    # Non-ASCII bytes become separate "\xNN" literals so no hex digit can follow an escape
    out = re.sub(rb"[\x80-\xff]", lambda m: b'" "\\x%02X" "' % m.group(0)[0], out)
    return out.replace(b'"" ', b"")


def main():
    with open(TS_FILE, "rb") as f:
        ts = f.read().replace(b"\r", b"")
    match = re.search(rb"<name>UASWarning</name>(.*?)</context>", ts, re.S)
    if not match:
        sys.exit("No UASWarning context in " + TS_FILE)

    keys = []
    seen = set()
    for source in re.findall(rb"<source>(.*?)</source>", match.group(1), re.S):
        key = unescape_xml(source)
        if not CONVERSION.search(key) or key in seen:
            continue
        seen.add(key)
        literal = CONVERSION.sub(b"", key)
        if len(re.findall(rb"[A-Za-z]", literal)) < 4:
            continue  # placeholder-only keys would match any text
        keys.append(key)

    with open(OUT_FILE, "wb") as f:
        f.write(HEADER)
        for key in keys:
            f.write(b'    "' + c_literal(key) + b'",\n')
        f.write(b"};\n")
    print("Wrote %d keys to %s" % (len(keys), OUT_FILE))


if __name__ == "__main__":
    main()
